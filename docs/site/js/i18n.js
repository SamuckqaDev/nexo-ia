    const originalText = new Map();
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode(node) {
        return node.textContent.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
      }
    });
    while (walker.nextNode()) originalText.set(walker.currentNode, walker.currentNode.textContent);

    function translatePage(language) {
      const dictionary = translations[language] || {};
      for (const [node, english] of originalText) {
        const trimmed = english.trim();
        const translated = dictionary[trimmed];
        node.textContent = translated
          ? english.replace(trimmed, translated)
          : english;
      }
      document.documentElement.lang = language;
      document.title = language === "pt-BR" ? "Nexo IA — Produto e Identidade" : "Nexo IA — Product and Identity";
      const docsSearch = document.querySelector("#docs-search");
      if (docsSearch) docsSearch.placeholder = language === "pt-BR"
        ? "Pesquisar requisitos, IDs, arquitetura..."
        : "Search requirements, IDs, architecture...";
      document.querySelectorAll("[data-language]").forEach((button) => {
        const active = button.dataset.language === language;
        button.classList.toggle("active", active);
        button.setAttribute("aria-pressed", String(active));
      });
      localStorage.setItem("nexo-ia-language", language);
    }

    document.addEventListener("click", (event) => {
      const button = event.target.closest("[data-language]");
      if (button) translatePage(button.dataset.language);
    });

    const savedLanguage = localStorage.getItem("nexo-ia-language");
    const browserLanguage = navigator.language.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
    translatePage(savedLanguage || browserLanguage);
