import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docsRoot = resolve(projectRoot, "docs");
const output = resolve(docsRoot, "site/js/docs-data.js");
const excluded = new Set(["index.html"]);

const names = (await readdir(docsRoot))
  .filter((name) => name.endsWith(".md") && !excluded.has(name))
  .sort();

const documents = await Promise.all(names.map(async (name) => {
  const markdown = await readFile(resolve(docsRoot, name), "utf8");
  const title = markdown.match(/^#\s+(.+)$/m)?.[1]?.trim() || name.replace(/\.md$/, "");
  return { id: name.replace(/\.md$/, "").toLowerCase(), file: name, title, markdown };
}));

const banner = "// Generated by scripts/build-docs-data.mjs. Do not edit manually.\n";
await writeFile(output, `${banner}window.NEXO_DOCS = ${JSON.stringify(documents)};\n`, "utf8");
console.log(`Generated ${documents.length} documents in ${output}`);
